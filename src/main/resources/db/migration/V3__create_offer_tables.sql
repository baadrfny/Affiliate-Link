CREATE TABLE offer_offers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertiser_id BIGINT       NOT NULL,   -- no FK: this table belongs to another module's data
    title         VARCHAR(255) NOT NULL,
    description   TEXT,
    landing_url   VARCHAR(500) NOT NULL,
    niche         VARCHAR(30)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_offer_offers_advertiser ON offer_offers (advertiser_id);

CREATE TABLE offer_tags (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE offer_offers_tags (
    offer_id BIGINT NOT NULL,
    tag_id   BIGINT NOT NULL,
    PRIMARY KEY (offer_id, tag_id),
    CONSTRAINT fk_offers_tags_offer FOREIGN KEY (offer_id) REFERENCES offer_offers (id),
    CONSTRAINT fk_offers_tags_tag   FOREIGN KEY (tag_id)   REFERENCES offer_tags (id)
);

CREATE TABLE offer_campaigns (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id     BIGINT         NOT NULL,
    name         VARCHAR(255)   NOT NULL,
    start_date   DATE           NOT NULL,
    end_date     DATE           NOT NULL,
    budget       NUMERIC(15, 2) NOT NULL,
    payout_model VARCHAR(20)    NOT NULL,
    payout_value NUMERIC(15, 2) NOT NULL,
    status       VARCHAR(20)    NOT NULL DEFAULT 'DRAFT',
    CONSTRAINT fk_campaigns_offer FOREIGN KEY (offer_id) REFERENCES offer_offers (id)
);

CREATE INDEX idx_offer_campaigns_offer  ON offer_campaigns (offer_id);
CREATE INDEX idx_offer_campaigns_status ON offer_campaigns (status);
